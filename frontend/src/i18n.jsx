const DICT = Object.fromEntries(Object.entries(T).map(([lang, arr]) => [lang, Object.fromEntries(K.map((k, i) => [k, arr[i]]))]))

const LangCtx = createContext({ lang: 'en', setLang: () => {}, t: (k) => DICT.en[k] || k })

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem('smartyield_lang') || 'en')
  useEffect(() => {
    localStorage.setItem('smartyield_lang', lang)
    document.documentElement.lang = lang
    document.documentElement.dir = RTL.has(lang) ? 'rtl' : 'ltr'
  }, [lang])
  const t = (k) => DICT[lang]?.[k] || DICT.en[k] || k
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>
}

export const useT = () => useContext(LangCtx)

export function LanguageSelect({ style }) {
  const { lang, setLang, t } = useT()
  return (
    <label style={{ display: 'flex', flexDirection: 'column', gap: 4, ...style }}>
      <span style={{ fontSize: '.8rem', opacity: .85 }}>🌐 {t('language')}</span>
      <select value={lang} onChange={(e) => setLang(e.target.value)} aria-label="Language">
        {LANGUAGES.map(([code, label]) => <option key={code} value={code}>{label}</option>)}
      </select>
    </label>
  )
}

