"""Step 7 - write docs/EXPERIMENTS.md from the measured result files.

Every number in the generated document is read from outputs/*.json|csv. None
is typed by hand, so the documentation cannot drift from the experiments.

Usage: python scripts/07_write_results.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from smartyield import config  # noqa: E402

O = config.OUTPUTS_DIR
MODELS = ["Mean baseline", "Linear Regression", "Ridge Regression", "Random Forest", "SVR", "XGBoost"]


def j(name):
    p = O / name
    return json.loads(p.read_text()) if p.exists() else None


def f(v, d=3):
    try:
        return f"{float(v):.{d}f}"
    except (TypeError, ValueError):
        return "–"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    L = ["# Experimental evaluation", "",
         "_Generated by `scripts/07_write_results.py` from `outputs/`. Every value is a real measurement "
         "from this repository's pipeline. Nothing is illustrative._", ""]
    ex = j("experiments_summary.json") or {}

    # ---------------- data
    nd = j("ndvi_validation.json")
    clean = j("data_cleaning_log.json")
    L += ["## 0. Data", ""]
    if clean:
        L += [table(["file", "rows", "plots kept", "missing yield", "out of range"],
                    [[c["file"], c["rows"], c["plots"], c["dropped_missing"], c["dropped_out_of_range"]] for c in clean]), ""]
    inv = j("raster_inventory.json")
    if inv:
        L += [f"Orthomosaics processed: **{len(inv)}** flights; plot-flight rows: "
              f"**{sum(r['plots'] for r in inv)}**.", ""]
    if nd:
        per = "; ".join(f"{k}: r = **{f(v['r'])}** (n = {v['n']})" for k, v in nd["per_trial"].items())
        L += [f"NDVI validation against the dataset-provided per-plot NDVI (after registration correction): {per}. "
              f"Pooled over both seasons r = {f(nd['pearson_r'])}, mean bias {f(nd['bias'])}. Each season's absolute NDVI "
              "level is offset differently (radiometric processing), so the per-trial values are the meaningful ones "
              "(see DATASETS.md §3).", ""]

    # ---------------- exp1
    e1 = ex.get("exp1_preprocessing")
    L += ["## Experiment 1 – Image preprocessing", "", "![](figures/exp1_preprocessing.png)", ""]
    if e1:
        df = pd.DataFrame(e1["stats"])
        L += [table(["image", "stage", "noise σ (Immerkær)", "RMS contrast", "channel-mean spread"],
                    [[r.image, r.stage, f(r.noise_sigma, 2), f(r.rms_contrast, 1), f(r.channel_mean_spread, 1)]
                     for r in df.itertuples()]), ""]
        rows = []
        for cond, v in e1["exg_segmentation_effect"].items():
            rows.append([cond, f(v["raw"]["iou"]), f(v["preprocessed"]["iou"]),
                         f(v["preprocessed"]["iou"] - v["raw"]["iou"])])
        L += [f"Effect on ExG+Otsu vegetation segmentation (IoU vs human masks, {e1['n_images']} PhenoBench test images):", "",
              table(["condition", "IoU raw", "IoU preprocessed", "Δ"], rows), ""]

    # ---------------- exp2
    s = j("segmentation_metrics.json")
    L += ["## Experiment 2 – Crop segmentation", ""]
    if s:
        rows = [[n, f(r["iou"]), f(r["dice"]), f(r["precision"]), f(r["recall"]), f(r["accuracy"]),
                 f"{f(r['mean_image_iou'])} ± {f(r['std_image_iou'])}"]
                for n, r in (("U-Net (CNN)", s["test_unet"]), ("ExG + Otsu (baseline)", s["test_exg_otsu_baseline"]))]
        L += [f"Training: {s['n_train']} images, model selection: {s['n_model_selection_val']} images, "
              f"held-out test: {s['test_unet']['n_images']} images ({s['test_split']}). "
              f"CPU training time {f(s['train_seconds'] / 60, 1)} min.", "",
              table(["method", "IoU", "Dice", "precision", "recall", "pixel acc.", "per-image IoU"], rows), "",
              "![](figures/exp2_segmentation_examples.png)", "", "![](figures/exp2_training_curve.png)", ""]
    e2b = ex.get("exp2b_rice_mask_agreement")
    if e2b:
        L += ["**Transfer to rice (agreement, not accuracy).** The rice imagery has no human masks, so the RGB masks are "
              "compared with the physically based NDVI-Otsu mask on the same orthomosaic crops:", "",
              table(["image", "NDVI cover", "U-Net IoU vs NDVI", "ExG-Otsu IoU vs NDVI"],
                    [[r["image"], f(r["ndvi_cover"]), f(r["unet_vs_ndvi"]["iou"]), f(r["exg_vs_ndvi"]["iou"])] for r in e2b]),
              "", "Caveat: mid-season rice canopies are nearly closed (high NDVI cover). In that case the agreement mostly "
              "shows that a method does not miss canopy (few false negatives). It is weak evidence about gaps and edges. "
              "The rigorous accuracy test is the human-annotated PhenoBench test set above.", "",
              f"RGB vegetation-mask method used by the app and the RGB training features: `{config.RGB_SEG_METHOD}`.", ""]
        for r in e2b:
            L += [f"![](figures/exp2b_rice_agreement_{Path(r['image']).stem}.png)", ""]

    # ---------------- exp3
    e3 = ex.get("exp3_crop_condition")
    L += ["## Experiment 3 – Crop health analysis", "", "![](figures/exp3_crop_condition.png)", ""]
    if e3:
        t = pd.DataFrame(e3["tests"])
        L += ["Mid-season flight per site-season. N-dose effect: Mann-Whitney U. Yield-tercile effect: Kruskal-Wallis. "
              "ρ: Spearman correlation with measured yield.", "",
              table(["site-season", "feature", "mean N100", "mean N200", "p (N)", "mean low-yield", "mean high-yield",
                     "p (tercile)", "ρ yield"],
                    [[r.site_season, r.feature, f(r.mean_N100), f(r.mean_N200), f(r.mannwhitney_p_N, 4),
                      f(r.mean_low_yield), f(r.mean_high_yield), f(r.kruskal_p_tercile, 4), f(r.spearman_rho_yield)]
                     for r in t.itertuples()]), ""]
        hc = pd.DataFrame(e3["health_class_yield"])
        L += ["Measured yield of plots per NDVI health class under two schemes: (a) absolute breaks calibrated on the "
              f"pooled data (poor < {f(e3['health_calibration']['poor_below'])}, healthy ≥ {f(e3['health_calibration']['healthy_from'])}); "
              "(b) relative within-image percentiles (20/60), the scheme the app uses. Under (a), whole site-seasons fall into "
              "one class (sensor and processing differences dominate). That is why the app uses (b).", "",
              table(["scheme", "site-season", "class", "plots", "mean yield t/ha", "SD"],
                    [[r.scheme, r.site_season, r.health_class, r.n_plots, f(r.mean_yield_t_ha, 2), f(r.sd_yield, 2)]
                     for r in hc.itertuples()]), ""]

    # ---------------- exp4
    L += ["## Experiment 4 – Yield prediction model comparison", "",
          "Protocol P1: grouped 5-fold CV with whole replicate blocks held out, and nested grouped grid search for "
          "hyper-parameters. Image level = one prediction per drone image of a plot. Plot level = mean over a plot's flights.", ""]
    for track, label in (("ms", "Multispectral track"), ("rgb", "RGB-only track")):
        r = j(f"yield_results_{track}.json")
        if not r:
            continue
        rows = []
        for n in MODELS:
            if n not in r["P1_grouped_cv"]:
                continue
            i, p = r["P1_grouped_cv"][n]["image_level"], r["P1_grouped_cv"][n]["plot_level"]
            rows.append([("**" + n + "**") if n == r["selected_model"] else n, f(i["MAE"]), f(i["MSE"]), f(i["RMSE"]),
                         f(i["R2"]), f(i["MAPE_%"], 1), f(p["RMSE"]), f(p["R2"])])
        L += [f"### {label}: {r['n_rows']} images of {r['n_plots']} plots, {len(r['features'])} features, "
              f"site-seasons {', '.join(r['site_seasons'])}", "",
              table(["model", "MAE", "MSE", "RMSE", "R²", "MAPE %", "plot RMSE", "plot R²"], rows), "",
              f"Selected: **{r['selected_model']}** ({r['selection_rule']}). Split-conformal 90 % interval half-width: "
              f"**±{f(r['conformal_q90_t_ha'], 2)} t/ha** (empirical OOF coverage {f(100 * r['conformal_coverage_check'], 1)} %).", "",
              f"![](figures/exp4_pred_vs_actual_{track}.png)", "", f"![](figures/exp4_feature_importance_{track}.png)", ""]
    L += ["![](figures/exp4_model_comparison.png)", ""]

    # feature-mode ablation (absolute vs absolute + image-relative), parsed from the training logs
    import re
    abl = {}
    for mode in ("abs", "absrel"):
        lp = O / f"train_ms_{mode}.log"
        if lp.exists():
            for m in re.finditer(r"\[P1\] (.+?)\s+RMSE ([\d.]+) MAE ([\d.]+) R2 (-?[\d.]+)", lp.read_text()):
                abl.setdefault(m[1].strip(), {})[mode] = (float(m[2]), float(m[4]))
    if abl:
        (O / "feature_mode_ablation.json").write_text(json.dumps(abl, indent=2))
        L += ["### Feature-mode ablation (multispectral, P1 grouped CV)", "",
              "`abs` = absolute features. `absrel` = absolute + image-relative features (feature minus its median over the "
              "same drone image). Pre-specified rule: use the mode whose selected model has the lower P1 RMSE. The RGB "
              "track follows the multispectral decision (CPU-time budget).", "",
              table(["model", "RMSE abs", "R² abs", "RMSE absrel", "R² absrel"],
                    [[n, f(v.get("abs", (None,))[0]), f(v.get("abs", (None, None))[1]),
                      f(v.get("absrel", (None,))[0]), f(v.get("absrel", (None, None))[1])] for n, v in abl.items()]), ""]

    # ---------------- exp5
    L += ["## Experiment 5 – Generalisation to unseen fields and seasons", ""]
    for track, label in (("ms", "Multispectral"), ("rgb", "RGB only")):
        r = j(f"yield_results_{track}.json")
        if not r or not r["P2_leave_site_season_out"]:
            continue
        ss = list(next(iter(r["P2_leave_site_season_out"].values())).keys())
        rows = [[n] + [f"{f(r['P2_leave_site_season_out'][n][s]['image_level']['RMSE'], 2)} / "
                       f"{f(r['P2_leave_site_season_out'][n][s]['image_level']['R2'], 2)}" for s in ss]
                for n in MODELS if n in r["P2_leave_site_season_out"]]
        L += [f"**{label}: leave-one-site-season-out (RMSE t/ha / R²)**", "", table(["model"] + [f"test = {s}" for s in ss], rows), ""]
        if r["P3_temporal_2022_to_2023"]:
            rows = [[n, f(v["image_level"]["RMSE"]), f(v["image_level"]["R2"]), f(v["plot_level"]["RMSE"]), f(v["plot_level"]["R2"])]
                    for n, v in r["P3_temporal_2022_to_2023"].items()]
            L += [f"**{label}: train 2022 → test 2023**", "", table(["model", "RMSE", "R²", "plot RMSE", "plot R²"], rows), ""]
    e5 = ex.get("exp5_generalisation")
    if e5:
        L += ["Accuracy by flight date (growth stage), selected model, P1 out-of-fold:", ""]
        for track, v in e5.items():
            L += [table(["track", "site-season", "flight", "DOY", "RMSE", "R²"],
                        [[track, d["site_season"], d["flight_date"], d["doy"], f(d["RMSE"]), f(d["R2"])] for d in v["per_flight_P1"]]), ""]
        L += ["![](figures/exp5_r2_by_growth_stage.png)", ""]

    # ---------------- exp6
    e6 = ex.get("exp6_field_level")
    L += ["## Experiment 6 – Field-level prediction", ""]
    if e6:
        for track in ("ms", "rgb"):
            if track not in e6:
                continue
            v = e6[track]
            L += [f"**{track} track** (protocol `{v['protocol']}`: every prediction is for a site-season held out from training)", "",
                  table(["level", "n", "RMSE", "MAE", "R²"],
                        [["plot", v["plot_level"]["n"], f(v["plot_level"]["RMSE"]), f(v["plot_level"]["MAE"]), f(v["plot_level"]["R2"])],
                         ["region (block × N dose)", v["n_regions"], f(v["regional_block_x_N_level"]["RMSE"]),
                          f(v["regional_block_x_N_level"]["MAE"]), f(v["regional_block_x_N_level"]["R2"])]]), "",
                  f"Regional rank agreement (Spearman): {f(v['regional_spearman'])}", "",
                  table(["field (site-season)", "plots", "actual mean t/ha", "predicted mean t/ha", "abs. error", "% error"],
                        [[x["site_year"], x["n_plots"], f(x["actual_mean"], 2), f(x["pred_mean"], 2), f(x["abs_error_t_ha"], 2),
                          f(x["pct_error"], 1)] for x in v["field_level"]]), ""]
        if e6.get("gridded_maps"):
            L += ["**Gridded yield maps produced by the application pipeline** on real orthomosaic crops "
                  "(non-overlapping ~1 m zones, aggregated by area). The model includes these site-seasons, so these maps "
                  "demonstrate the pipeline. The held-out accuracy is in the tables above.", "",
                  table(["image", "zones (crop)", "zone size m", "pred. field t/ha", "90 % PI", "measured trial mean t/ha",
                         "cropped ha", "production t"],
                        [[m["image"], f"{m['zones']} ({m['crop_zones']})", f(m["zone_size_m"], 2), f(m["pred_field_t_ha"], 2),
                          f"{f(m['pi90'][0], 2)}–{f(m['pi90'][1], 2)}", f(m["actual_trial_mean_t_ha"], 2),
                          f(m["cropped_area_ha"], 4), f(m["production_t"], 3)] for m in e6["gridded_maps"]]), ""]
            for m in e6["gridded_maps"]:
                L += [f"![](figures/exp6_field_map_{m['image'].split('_')[0]}.png)", ""]

    # ---------------- exp7
    t7 = O / "exp7_pytest.txt"
    L += ["## Experiment 7 – Application testing", ""]
    if t7.exists():
        L += ["```", t7.read_text().strip()[-3000:], "```", ""]
    (config.ROOT / "docs" / "EXPERIMENTS.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote docs/EXPERIMENTS.md", len(L), "lines")
    write_resume_and_readme(s, ex)


def write_resume_and_readme(seg, ex):
    ms, rgb = j("yield_results_ms.json"), j("yield_results_rgb.json")
    nd = j("ndvi_validation.json")

    def best(r):
        m = r["selected_model"]
        return m, r["P1_grouped_cv"][m]["image_level"], r["P1_grouped_cv"][m]["plot_level"], r["P1_grouped_cv"]["Mean baseline"]["image_level"]

    lines = []
    if ms:
        m, i, p, b = best(ms)
        lines.append(f"* Multispectral track: **{m}**, image-level RMSE **{f(i['RMSE'], 2)} t/ha** (R² {f(i['R2'], 2)}, "
                     f"MAPE {f(i['MAPE_%'], 1)} %) vs mean-baseline RMSE {f(b['RMSE'], 2)}; plot-level (multi-flight) RMSE "
                     f"{f(p['RMSE'], 2)} t/ha, R² {f(p['R2'], 2)}. Grouped CV over {ms['n_plots']} plots / {ms['n_rows']} drone images.")
    if rgb:
        m, i, p, b = best(rgb)
        lines.append(f"* RGB-only track: **{m}**, RMSE **{f(i['RMSE'], 2)} t/ha** (R² {f(i['R2'], 2)}) vs baseline {f(b['RMSE'], 2)}.")
    if seg:
        lines.append(f"* Segmentation on held-out human-annotated UAV images: U-Net IoU **{f(seg['test_unet']['iou'])}** / Dice "
                     f"{f(seg['test_unet']['dice'])} vs ExG+Otsu IoU {f(seg['test_exg_otsu_baseline']['iou'])}.")
    if ms and ms["P2_leave_site_season_out"]:
        m = ms["selected_model"]
        r2s = ", ".join(f"{k}: R² {f(v['image_level']['R2'], 2)}" for k, v in ms["P2_leave_site_season_out"][m].items())
        lines.append(f"* Unseen site-season test ({m}, multispectral): {r2s}.")
    if nd:
        per = ", ".join(f"{k}: r = {f(v['r'], 2)} (n = {v['n']})" for k, v in nd["per_trial"].items())
        lines.append(f"* Plot NDVI vs the dataset authors' NDVI, per trial (after registration correction): {per}.")
    results = "\n".join(lines)

    readme = config.ROOT / "README.md"
    txt = readme.read_text(encoding="utf-8")
    a, b_ = txt.index("<!-- RESULTS:START -->"), txt.index("<!-- RESULTS:END -->")
    readme.write_text(txt[:a] + "<!-- RESULTS:START -->\n## Headline results (measured, grouped validation)\n\n" + results +
                      "\n\nFull tables and figures: [docs/EXPERIMENTS.md](docs/EXPERIMENTS.md).\n" + txt[b_:], encoding="utf-8")

    n_plots = ms["n_plots"] if ms else "–"
    n_imgs = ms["n_rows"] if ms else "–"
    R = ["# Resume and interview material", "",
         "## Project title",
         "SmartYield AI – Drone-Based Crop Yield Estimation and Agricultural Monitoring (Computer Vision + ML)", "",
         "## Resume bullets (numbers are the measured results in docs/EXPERIMENTS.md)", "",
         f"* Built an end-to-end drone crop-monitoring system (PyTorch, OpenCV, scikit-learn, XGBoost, FastAPI, React) that segments "
         f"crops, maps crop health and predicts rice yield (t/ha) per 1 m zone and per field from UAV imagery.",
         f"* Assembled a supervised dataset from real UAV multispectral orthomosaics and harvest measurements ({n_plots} plots, "
         f"{n_imgs} plot-images, 2 sites × 2 seasons). Validated NDVI band order against the dataset authors' NDVI.",
         *[ln.replace("* ", "* Achieved ", 1) if ln.startswith("* Multispectral") else ln for ln in lines[:3]],
         "* Prevented data leakage with grouped (block / site / season) nested cross-validation and pipeline-contained preprocessing. "
         "Added split-conformal 90 % prediction intervals and out-of-distribution warnings.",
         "* Shipped a FastAPI + SQLite backend (JWT auth, validated uploads, background analysis jobs, PDF reports) and a React "
         "dashboard with history, actual-vs-predicted tracking and model-performance views. Covered by a pytest suite.", "",
         "## 30-second pitch",
         "Farmers need a yield estimate before harvest. I take drone images, separate the crop from water and soil with a U-Net, "
         "compute vegetation indices (true NDVI when the camera has a NIR band) and canopy texture, and feed them to a regression "
         "model trained on real harvest yields. The hard part was honest evaluation: every plot is photographed several times, so "
         "random splits leak. I split by field block, site and season, and report how accuracy drops on unseen seasons.", "",
         "## Likely interview questions",
         "* **Why not random train/test split?** Rows of the same plot share one yield, so a random split leaks the label. Grouped CV keeps all of a plot in one fold.",
         "* **NDVI from RGB?** Impossible: NDVI needs NIR. The RGB track uses ExG / VARI / GLI and labels them as such.",
         "* **Why is R² modest?** Plot yields come from ~12 harvested plants (sampling noise), and canopy greenness saturates in dense rice. "
         "The model still beats the mean baseline under grouped CV. Unseen-season results show the generalisation limit.",
         "* **Why did XGBoost/RF/SVR/LR win or lose?** See Experiment 4. The selection used validation RMSE only, never the test seasons.",
         "* **How are field totals computed?** Non-overlapping ~1 m zones. Area-weighted mean t/ha × cropped area (GSD from the GeoTIFF, or from the user's field area).",
         "* **Uncertainty?** Split-conformal: the 90th percentile of out-of-fold absolute residuals gives a ± band with ~90 % empirical coverage.",
         "* **What would you do next?** Add more seasons and sites, use multi-temporal models (growth curves), weather covariates, and calibrate consumer-camera RGB."]
    (config.ROOT / "docs" / "RESUME.md").write_text("\n".join(R) + "\n", encoding="utf-8")
    print("wrote README results + docs/RESUME.md")


if __name__ == "__main__":
    main()
